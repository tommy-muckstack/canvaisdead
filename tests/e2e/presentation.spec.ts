import { waitForDesignSave } from "./fixtures";
import { expect, test } from "./fixtures";
import { capturePresentation, createPresentationDeck } from "../../scripts/parity/presentation-evidence";

test("presentation navigates pages, autoplays, and keeps notes in presenter view", async ({ page, context }, testInfo) => {
  const editor = await createPresentationDeck(page);
  await page.getByRole("button", { name: "Present", exact: true }).click();
  await expect(page.getByRole("spinbutton", { name: "Go to page" })).toHaveValue("2");
  await page.getByRole("main", { name: "Presentation", exact: true }).focus();
  await page.keyboard.press("Home");
  await expect(page.getByRole("spinbutton", { name: "Go to page" })).toHaveValue("1");
  await expect(page.getByText("Private speaker note", { exact: true })).toHaveCount(0);
  await page.getByLabel("Seconds per page").selectOption("2");
  await page.getByRole("button", { name: "Start autoplay", exact: true }).click();
  await expect(page.getByRole("spinbutton", { name: "Go to page" })).toHaveValue("2", { timeout: 4000 });
  await page.screenshot({ path: testInfo.outputPath("presentation.png") });
  await capturePresentation(page, testInfo.project.name, "after", "standard");
  await page.getByRole("button", { name: "Exit presentation", exact: true }).click();
  await expect(page).toHaveURL(editor);
  // Reopening the editor currently selects page 1. Explicitly start on page 2
  // so the Previous assertion actually exercises backward navigation.
  await page.getByRole("tab", { name: "Page 2", exact: true }).click();
  await expect(page.getByRole("tab", { name: "Page 2", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("button", { name: "More present options", exact: true }).click();
  const popup = context.waitForEvent("page");
  await page.getByRole("button", { name: "Presenter view", exact: true }).click();
  const audience = await popup;
  await expect(page.getByRole("heading", { name: "Notes", exact: true })).toBeVisible();
  await expect(page.getByRole("spinbutton", { name: "Go to page" })).toHaveValue("2");
  await expect(audience.getByRole("spinbutton", { name: "Go to page" })).toHaveValue("2");
  await page.getByRole("button", { name: "Previous page", exact: true }).click();
  await expect(page.getByText("Private speaker note", { exact: true })).toBeVisible();
  await expect(audience.getByRole("spinbutton", { name: "Go to page" })).toHaveValue("1");
  await expect(audience.getByText("Private speaker note", { exact: true })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath("presenter-notes.png") });
  await capturePresentation(page, testInfo.project.name, "after", "presenter");
  await capturePresentation(audience, testInfo.project.name, "after", "audience");
  await audience.close();
});

test("presentation live edits can be paused and resumed without changing slides", async ({ page, context }) => {
  const editor = await createPresentationDeck(page);
  await page.getByRole("button", { name: "Text", exact: true }).click();
  await page.getByRole("button", { name: "Add a heading", exact: true }).click();
  const editHeadline = async (target: typeof page, value: string) => {
    await target.getByTestId("page").locator("text").dblclick();
    await target.getByRole("textbox", { name: "Edit text", exact: true }).fill(value);
    await target.getByRole("textbox", { name: "Page title", exact: true }).focus();
    await expect(target.getByRole("textbox", { name: "Edit text", exact: true })).toHaveCount(0);
    await waitForDesignSave(target);
  };
  await editHeadline(page, "Live slide");
  const author = await context.newPage();
  await author.goto(editor);
  await author.getByRole("tab", { name: "Page 2", exact: true }).click();
  await page.getByRole("button", { name: "Present", exact: true }).click();
  const slide = page.getByTestId("presentation-slide"), current = page.getByRole("spinbutton", { name: "Go to page" });
  await expect(current).toHaveValue("2"); await expect(slide).toContainText("Live slide");
  const live = page.getByRole("checkbox", { name: "Live edits", exact: true });
  await expect(live).toBeVisible(); await live.uncheck();
  await editHeadline(author, "Paused update");
  await author.getByRole("button", { name: "Notes", exact: true }).click();
  await author.getByLabel("Notes for page 2").fill("Private live note");
  await author.getByRole("button", { name: "Close notes", exact: true }).click();
  await waitForDesignSave(author);
  await expect(live).not.toBeChecked(); await expect(slide).toContainText("Live slide");
  await live.check();
  await expect(slide).toContainText("Paused update"); await expect(current).toHaveValue("2");
  await editHeadline(author, "Visible update");
  await expect(slide).toContainText("Visible update"); await expect(current).toHaveValue("2");
  await expect(page.getByText("Private live note", { exact: true })).toHaveCount(0);
  await page.getByRole("main", { name: "Presentation", exact: true }).focus(); await page.keyboard.press("Escape");
  await expect(page).toHaveURL(editor);
  await page.getByRole("tab", { name: "Page 2", exact: true }).click();
  const returnedHeadline = await page.getByTestId("page").locator("text").textContent();
  if (process.env.CI) console.log("PARITY_PRESENTATION_RETURN " + JSON.stringify({ viewport: page.viewportSize(), returnedHeadline, latestSavedHeadline: "Visible update" }));
  await page.reload(); await page.getByRole("tab", { name: "Page 2", exact: true }).click();
  await expect(page.getByTestId("page").locator("text")).toHaveText("Visible update");
  await author.close();
});

test("presenter windows synchronize navigation and reconnect without exposing notes", async ({ page, context }) => {
  await createPresentationDeck(page);
  await page.getByRole("button", { name: "More present options", exact: true }).click();
  const popup = context.waitForEvent("page");
  await page.getByRole("button", { name: "Presenter view", exact: true }).click();
  const audience = await popup, current = page.getByRole("spinbutton", { name: "Go to page" });
  await expect(current).toHaveValue("2");
  await expect(audience.getByRole("spinbutton", { name: "Go to page" })).toHaveValue("2");
  await audience.getByRole("button", { name: "Previous page", exact: true }).click();
  await expect(current).toHaveValue("1");
  await expect(page.getByText("Private speaker note", { exact: true })).toBeVisible();
  await expect(audience.getByText("Private speaker note", { exact: true })).toHaveCount(0);
  await audience.reload(); await expect(audience.getByRole("spinbutton", { name: "Go to page" })).toHaveValue("1");
  const isolated = await context.newPage(), independent = new URL(audience.url());
  independent.searchParams.set("session", "00000000-0000-4000-8000-000000000001");
  independent.searchParams.set("page", "2");
  await isolated.goto(independent.href);
  await expect(isolated.getByRole("spinbutton", { name: "Go to page" })).toHaveValue("2");
  await page.getByRole("button", { name: "Next page", exact: true }).click();
  await expect(audience.getByRole("spinbutton", { name: "Go to page" })).toHaveValue("2");
  await page.getByRole("button", { name: "Previous page", exact: true }).click();
  await expect(audience.getByRole("spinbutton", { name: "Go to page" })).toHaveValue("1");
  await expect(isolated.getByRole("spinbutton", { name: "Go to page" })).toHaveValue("2");
  await expect(isolated.getByText("Private speaker note", { exact: true })).toHaveCount(0);
  await audience.close();
  const reopened = context.waitForEvent("page"); await page.getByRole("button", { name: "Open audience window", exact: true }).click();
  const replacement = await reopened;
  await expect(replacement.getByRole("spinbutton", { name: "Go to page" })).toHaveValue("1");
  await expect(replacement.getByText("Private speaker note", { exact: true })).toHaveCount(0);
  await replacement.close(); await isolated.close();
});
