import { waitForDesignSave } from "./fixtures";
import { readFile } from "node:fs/promises";
import { expect, test } from "./fixtures";

test("page edits survive switching, duplication, reorder, undo, reload and selected-page export", async ({ page }, testInfo) => {
  await page.goto("/canvaisdead/login");
  const cookies = page.getByRole("button", { name: "Accept all cookies" });
  if (await cookies.isVisible()) await cookies.click();
  await page.getByRole("button", { name: "Use the demo account" }).click();
  await expect(page.getByTestId("designs")).toBeVisible();
  await page.locator(".cx-qc").getByRole("button", { name: "Presentation", exact: true }).click();
  const canvas = page.getByTestId("page");
  await expect(canvas).toBeVisible();
  await page.getByRole("button", { name: "Text", exact: true }).click();
  await page.getByRole("button", { name: "Add a heading", exact: true }).click();
  await canvas.locator("text").dblclick();
  await page.getByRole("textbox", { name: "Edit text", exact: true }).fill("A preserved first page");
  // Clicking Add page must commit the textarea blur before the page operation.
  await page.getByRole("button", { name: "Add page", exact: true }).click();
  await expect(page.getByLabel("Page count", { exact: true })).toHaveText("2 / 2");
  await expect(canvas.locator("text")).toHaveCount(0);
  await page.getByRole("textbox", { name: "Page title", exact: true }).fill("Details");
  await page.getByRole("button", { name: "Text", exact: true }).click();
  await page.getByRole("button", { name: "Add a heading", exact: true }).click();
  await canvas.locator("text").dblclick();
  await page.getByRole("textbox", { name: "Edit text", exact: true }).fill("Second page content");
  await page.getByRole("button", { name: "Duplicate page", exact: true }).click();
  await expect(page.getByLabel("Page count", { exact: true })).toHaveText("3 / 3");
  await expect(canvas.locator("text")).toContainText("Second page content");
  await page.getByRole("textbox", { name: "Page title", exact: true }).fill("Copy");
  await page.getByRole("button", { name: "Move page earlier", exact: true }).click();
  await expect(page.getByRole("tab", { name: "Page 2: Copy", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("button", { name: "Delete page", exact: true }).click();
  await expect(page.getByRole("tab")).toHaveCount(2);
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  await expect(page.getByRole("tab")).toHaveCount(3);
  await page.getByRole("tab", { name: "Page 1", exact: true }).click();
  await expect(canvas.locator("text")).toContainText("A preserved first page");
  await waitForDesignSave(page); await page.reload();
  await expect(page.getByRole("tab")).toHaveCount(3);
  await expect(canvas.locator("text")).toContainText("A preserved first page");
  await page.getByRole("button", { name: "Grid view", exact: true }).click();
  const first = page.getByRole("tab", { name: "Page 1", exact: true });
  await first.focus(); await first.press("End");
  const last = page.getByRole("tab", { name: "Page 3: Details", exact: true });
  await expect(last).toBeFocused();
  await expect(last).toHaveAttribute("aria-selected", "true");
  await page.screenshot({ path: testInfo.outputPath("page-grid.png") });
  await last.press("Enter");
  await expect(canvas).toBeVisible();
  await expect(canvas.locator("text")).toContainText("Second page content");
  await page.getByRole("button", { name: "Share", exact: true }).click();
  await page.getByRole("button", { name: "Download", exact: true }).click();
  await expect(page.locator(".cv-export-page")).toContainText("Page 3 of 3: Details");
  await page.getByLabel("File type", { exact: true }).selectOption("svg");
  await page.getByLabel("Select pages", { exact: true }).selectOption("current");
  const downloaded = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download", exact: true }).click();
  const download = await downloaded;
  expect(download.suggestedFilename()).toContain("-page-3.svg");
  const svg = await readFile((await download.path())!, "utf8");
  expect(svg).toContain("Second page content");
  expect(svg).not.toContain("A preserved first page");
  await page.screenshot({ path: testInfo.outputPath("multi-page-editor.png") });
});
