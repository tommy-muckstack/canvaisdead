import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { DesignArtwork, ArtworkElements, SVGArtwork } from "@/components/canva/Artwork";
import { designSVGNode, elementSVGNode, toSVG } from "@/lib/design/ops";
import { svgBlob, svgChunks, svgNode } from "@/lib/design/svg-tree";
import { layerThumbnailNode } from "@/lib/design/layers";
import { zipBlobs, zipFiles } from "@/lib/design/zip";
import type { CanvasDesign } from "@/lib/design/types";
import golden from "../fixtures/svg-artwork.json";

const design = golden.design as CanvasDesign;
describe("artwork DOM and bounded SVG output", () => {
  it("preserves the original renderer's geometry, paint, text layout and crop/flip composition", async () => {
    // Captured from the parent commit, not generated by the new geometry builder.
    const expected = golden.svg.replaceAll("&#160;", "\u00a0");
    expect(toSVG(design)).toBe(expected);
    expect(await (await svgBlob(designSVGNode(design))).text()).toBe(expected);
  });
  it("renders escaped text, SVG attributes, independent image sources and the editing exclusion in React", () => {
    const html = renderToStaticMarkup(createElement(DesignArtwork, { design }));
    expect(html).toContain('width="100%" height="100%"');
    expect(html).toContain('xml:space="preserve" style="white-space:pre"');
    expect(html).toContain('font-family="Test &quot;Font&quot;" font-size="24" font-weight="700" font-style="italic" letter-spacing="2.4000000000000004" text-decoration="underline line-through"');
    expect(html).toContain('stroke-width="3"'); expect(html).toContain('stroke-linecap="round"');
    expect(html).toContain('A&lt;&amp;&quot;😀'); expect(html.match(/<image /g)).toHaveLength(5);
    expect(html).toContain('viewBox="30 20 200 100"'); expect(html).toContain('matrix(-1 0 0 1 310 0)');
    const editing = renderToStaticMarkup(createElement("svg", null, createElement(ArtworkElements, { elements: design.els, hiddenId: "fixture-5" })));
    expect(editing).not.toContain("<text"); expect(editing.match(/<image /g)).toHaveLength(5);
    expect(renderToStaticMarkup(createElement(SVGArtwork, { node: layerThumbnailNode(design.els) }))).toContain('width="48" height="40"');
    expect(elementSVGNode({ ...design.els[6], src: undefined })).toBeNull();
  });
  it("escapes bounded text/attribute chunks without splitting emoji between Blob parts", async () => {
    const text = "a".repeat(16383) + "😀" + '<&"'.repeat(20_000), node = svgNode("text", { "font-family": text }, undefined, text);
    expect([...svgChunks(node)].every(part => part.length <= 6 * 16385)).toBe(true);
    const output = await (await svgBlob(node)).text();
    expect(output).not.toContain("�"); expect(output.match(/😀/g)).toHaveLength(2);
    expect(output).toContain("&lt;&amp;&quot;");
  });
  it("cancels within a single large SVG before returning any artifact", async () => {
    const controller = new AbortController(), pending = svgBlob(svgNode("text", {}, undefined, "a".repeat(3 * 1024 * 1024)), controller.signal);
    setTimeout(() => controller.abort(), 0);
    await expect(pending).rejects.toMatchObject({ name: "AbortError" });
  });
  it("packages Blob entries byte-for-byte like the existing ZIP writer and cancels during checksumming", async () => {
    const entries = [{ name: "résumé.svg", data: new TextEncoder().encode("<svg>😀</svg>") }, { name: "empty.svg", data: new Uint8Array() }];
    expect(await (await zipBlobs(entries.map(entry => ({ ...entry, data: new Blob([entry.data]) })))).arrayBuffer()).toEqual(await zipFiles(entries).arrayBuffer());
    const controller = new AbortController(), pending = zipBlobs([{ name: "big.svg", data: new Blob(["x".repeat(3 * 1024 * 1024)]) }], controller.signal);
    setTimeout(() => controller.abort(), 0); await expect(pending).rejects.toMatchObject({ name: "AbortError" });
  });
  it("rejects ZIP32 overflow before reading payloads", async () => {
    const tooBig = new Blob(["x"]); Object.defineProperty(tooBig, "size", { value: 0xffffffff });
    await expect(zipBlobs([{ name: "large.svg", data: tooBig }])).rejects.toThrow("fewer pages");
    await expect(zipBlobs([{ name: "../bad.svg", data: new Blob() }])).rejects.toThrow("filename");
  });
});
